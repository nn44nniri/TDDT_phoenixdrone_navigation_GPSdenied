def _validate_mosaic_sources(files, label):
    # Validate that source rasters can be mosaicked without semantic corruption.
    if not files:
        raise ValueError(f"At least one {label} raster is required.")
    reference = None
    for file in files:
        with rasterio.open(file) as ds:
            signature = {
                "crs": str(ds.crs),
                "count": ds.count,
                "dtype": tuple(ds.dtypes),
                "descriptions": tuple(ds.descriptions),
            }
            if reference is None:
                reference = signature
            elif signature != reference:
                raise ValueError(
                    f"Incompatible {label} raster for mosaic: {file}. "
                    "CRS, band count, data types, and band descriptions must match."
                )
    return reference


def _mosaic_to_file(files, output, bounds=None, bounds_crs="EPSG:4326"):
    # Extract and mosaic the requested extent into a GeoTIFF.
    sources = [rasterio.open(f) for f in files]
    try:
        target_bounds = None
        if bounds is not None:
            west, south, east, north = bounds
            if west >= east or south >= north:
                raise ValueError("Bounds must satisfy WEST < EAST and SOUTH < NORTH.")
            target_bounds = transform_bounds(
                bounds_crs, sources[0].crs, west, south, east, north, densify_pts=21
            )

        arr, out_transform = merge(
            sources,
            bounds=target_bounds,
            method="first",
            target_aligned_pixels=True,
            mem_limit=256,
        )
        if arr.size == 0 or arr.shape[1] == 0 or arr.shape[2] == 0:
            raise ValueError("The requested mosaic bounds do not intersect the input rasters.")

        output = Path(output)
        output.parent.mkdir(parents=True, exist_ok=True)
        profile = sources[0].profile.copy()
        block_x = min(256, arr.shape[2])
        block_y = min(256, arr.shape[1])
        block_x = max(16, (block_x // 16) * 16)
        block_y = max(16, (block_y // 16) * 16)
        profile.update(
            driver="GTiff",
            height=arr.shape[1],
            width=arr.shape[2],
            transform=out_transform,
            count=arr.shape[0],
            tiled=True,
            blockxsize=block_x,
            blockysize=block_y,
            compress="DEFLATE",
            BIGTIFF="IF_SAFER",
        )
        with rasterio.open(output, "w", **profile) as dst:
            dst.write(arr)
            for i, desc in enumerate(sources[0].descriptions, start=1):
                if desc:
                    dst.set_band_description(i, desc)
            dst.update_tags(**sources[0].tags())
            for i in range(1, sources[0].count + 1):
                tags = sources[0].tags(i)
                if tags:
                    dst.update_tags(i, **tags)

        with rasterio.open(output) as ds:
            bounds_wgs84 = transform_bounds(ds.crs, "EPSG:4326", *ds.bounds, densify_pts=21)
            metadata = {
                "output": str(output.resolve()),
                "shape": [ds.count, ds.height, ds.width],
                "crs": str(ds.crs),
                "bounds_projected": list(ds.bounds),
                "bounds_wgs84": list(bounds_wgs84),
                "resolution": [abs(ds.transform.a), abs(ds.transform.e)],
                "bands": list(band_map(ds).keys()),
            }
        return metadata
    finally:
        for src in sources:
            src.close()


