def expand(patterns):
    files = []
    for pattern in patterns:
        matches = glob.glob(pattern)
        files.extend(matches if matches else [pattern])
    unique = sorted({str(Path(f)) for f in files if Path(f).exists()})
    if not unique:
        raise FileNotFoundError("No input rasters matched.")
    return unique


def band_map(ds):
    return {
        (ds.descriptions[i-1] or f"band_{i}"): i
        for i in range(1, ds.count + 1)
    }


def info(files):
    geod = Geod(ellps="WGS84")
    rows = []
    all_bounds = []
    for file in files:
        with rasterio.open(file) as ds:
            b = transform_bounds(ds.crs, "EPSG:4326", *ds.bounds, densify_pts=21)
            all_bounds.append(b)
            rows.append({
                "file": file,
                "crs": str(ds.crs),
                "size": [ds.width, ds.height],
                "count": ds.count,
                "bounds_wgs84": b,
                "bands": list(band_map(ds).keys()),
            })
    west = min(b[0] for b in all_bounds)
    south = min(b[1] for b in all_bounds)
    east = max(b[2] for b in all_bounds)
    north = max(b[3] for b in all_bounds)
    _, _, width_m = geod.inv(west, (south+north)/2, east, (south+north)/2)
    _, _, height_m = geod.inv((west+east)/2, south, (west+east)/2, north)
    print(json.dumps({
        "files": rows,
        "mosaic_bounds_wgs84": [west, south, east, north],
        "approx_width_km": width_m/1000,
        "approx_height_km": height_m/1000,
        "approx_bounding_area_km2": width_m*height_m/1e6,
    }, indent=2))


def sample_file(file, lon, lat):
    """Read a WGS84 point without admitting edge, nodata or nonfinite pixels.

    Bounds are half-open in pixel-index space. The old <= bounds check could
    accept an exact outer border and address row=height or col=width. No
    nearest-neighbour extrapolation or height substitution is permitted.
    """
    if not all(math.isfinite(float(v)) for v in (lon, lat)) or not (-180 <= float(lon) <= 180 and -90 <= float(lat) <= 90):
        raise ValueError("WGS84_lon_lat_must_be_finite_and_in_range")
    with rasterio.open(file) as ds:
        if ds.crs is None:
            raise ValueError("raster_crs_missing")
        xs, ys = transform("EPSG:4326", ds.crs, [float(lon)], [float(lat)])
        x, y = xs[0], ys[0]
        if not (math.isfinite(x) and math.isfinite(y)):
            raise ValueError("projected_coordinate_nonfinite")
        row, col = ds.index(x, y)
        if not (0 <= row < ds.height and 0 <= col < ds.width):
            return None
        values = ds.read(window=Window(col, row, 1, 1), masked=True)[:, 0, 0]
        if len(values) != ds.count:
            raise ValueError("raster_read_incomplete")
        result = {
            "file": str(file),
            "pixel": {"row": row, "col": col},
            "projected_coordinate": [x, y],
        }
        for i, value in enumerate(values, start=1):
            name = ds.descriptions[i-1] or f"band_{i}"
            invalid = bool(np.ma.is_masked(value)) or not math.isfinite(float(value))
            result[name] = None if invalid else float(value)
        return result


def time_bin(hour):
    if 0 <= hour <= 5:
        return "00_06"
    if 6 <= hour <= 11:
        return "06_12"
    if 12 <= hour <= 17:
        return "12_18"
    if 18 <= hour <= 23:
        return "18_24"
    raise ValueError("hour must be between 0 and 23")


def load_centroid(csv_path, cluster_id):
    if not csv_path or cluster_id is None:
        return None
    with open(csv_path, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            if int(float(row["cluster_id"])) == int(round(cluster_id)):
                out = {}
                for k, v in row.items():
                    try:
                        out[k] = float(v)
                    except (TypeError, ValueError):
                        out[k] = v
                return out
    return None


def sanitize_for_json(obj):
    if isinstance(obj, dict):
        return {k: sanitize_for_json(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [sanitize_for_json(v) for v in obj]
    if isinstance(obj, tuple):
        return [sanitize_for_json(v) for v in obj]
    if isinstance(obj, np.generic):
        if np.isnan(obj):
            return None
        return obj.item()
    if isinstance(obj, float) and math.isnan(obj):
        return None
    return obj


def _band_index(ds, name):
    mapping = band_map(ds)
    if name not in mapping:
        raise KeyError(f"Band '{name}' not found in {ds.name}")
    return mapping[name]


def _downsample_step(height, width, max_grid):
    return max(1, int(math.ceil(max(height, width) / max_grid)))


def _grid_from_transform(ds, shape, step=1):
    rows = np.arange(0, shape[0], step)
    cols = np.arange(0, shape[1], step)
    xs = ds.transform.c + (cols + 0.5) * ds.transform.a
    ys = ds.transform.f + (rows + 0.5) * ds.transform.e
    return np.meshgrid(xs, ys)


def _read_downsampled_bands(ds, names, max_grid=140):
    step = _downsample_step(ds.height, ds.width, max_grid)
    arrays = {}
    for name in names:
        idx = _band_index(ds, name)
        arr = ds.read(idx).astype(np.float32)
        if ds.nodata is not None:
            arr = np.where(np.isclose(arr, ds.nodata), np.nan, arr)
        arrays[name] = arr[::step, ::step]
    xg, yg = _grid_from_transform(ds, (ds.height, ds.width), step=step)
    return arrays, xg, yg, step


def _safe_name(prefix):
    return prefix.replace(" ", "_").replace("/", "_")


def _pick_output_dir(terrain, climate, explicit_dir=None):
    if explicit_dir:
        outdir = Path(explicit_dir)
    else:
        base = Path(climate or terrain).resolve().parent
        outdir = base / "plotly_3d"
    outdir.mkdir(parents=True, exist_ok=True)
    return outdir


def _save_result_json(outdir, result, prefix):
    path = outdir / f"{prefix}_point_query.json"
    path.write_text(json.dumps(sanitize_for_json(result), indent=2, ensure_ascii=False), encoding="utf-8")
    return path


def generate_3d_plots(terrain_path, climate_path, hour, outdir, prefix, max_grid=140,
                      markers=None, magnetic_path=None, region_spec=None):
    try:
        import plotly.graph_objects as go
        from plotly.subplots import make_subplots
    except Exception as exc:
        raise RuntimeError(
            "Plotly is required for --plot3d. Install it with: pip install plotly"
        ) from exc

    if hour is None:
        raise ValueError("--plot3d requires --hour so that the climate time bin can be selected.")

    tb = time_bin(hour)
    prefix = _safe_name(prefix)

    with rasterio.open(terrain_path) as terrain_ds, rasterio.open(climate_path) as climate_ds:
        terrain_names = [
            "terrain_elevation_m",
            "terrain_slope_deg",
            "building_mask",
            "building_height_m",
            "road_class",
            "natural_obstacle_class",
            "artificial_obstacle_class",
        ]
        climate_names = [
            f"temperature_c_{tb}",
            f"relative_humidity_percent_{tb}",
            f"wind_u_east_ms_{tb}",
            f"wind_v_north_ms_{tb}",
            f"wind_vector_speed_ms_{tb}",
            f"wind_direction_from_deg_{tb}",
            f"climate_cluster_id_{tb}",
            f"cluster_confidence_{tb}",
        ]

        terrain, xg, yg, step = _read_downsampled_bands(terrain_ds, terrain_names, max_grid=max_grid)
        climate, _, _, _ = _read_downsampled_bands(climate_ds, climate_names, max_grid=max_grid)

    magnetic = None
    if magnetic_path and Path(magnetic_path).exists():
        with rasterio.open(magnetic_path) as magnetic_ds:
            magnetic_names = [
                "magnetic_anomaly_nt",
                "magnetic_anomaly_error_nt",
                "magnetic_source_code",
                "magnetic_anomaly_gradient_nt_per_m",
            ]
            magnetic, _, _, _ = _read_downsampled_bands(magnetic_ds, magnetic_names, max_grid=max_grid)

    dem = terrain["terrain_elevation_m"]
    slope = terrain["terrain_slope_deg"]
    building_mask = np.nan_to_num(terrain["building_mask"], nan=0.0)
    building_height = np.nan_to_num(terrain["building_height_m"], nan=0.0)
    roads = np.nan_to_num(terrain["road_class"], nan=0.0)
    natural_obs = np.nan_to_num(terrain["natural_obstacle_class"], nan=0.0)
    artificial_obs = np.nan_to_num(terrain["artificial_obstacle_class"], nan=0.0)

    temp = climate[f"temperature_c_{tb}"]
    rh = climate[f"relative_humidity_percent_{tb}"]
    wind_u = climate[f"wind_u_east_ms_{tb}"]
    wind_v = climate[f"wind_v_north_ms_{tb}"]
    wind_speed = climate[f"wind_vector_speed_ms_{tb}"]
    wind_dir = climate[f"wind_direction_from_deg_{tb}"]
    cluster_id = climate[f"climate_cluster_id_{tb}"]
    cluster_conf = climate[f"cluster_confidence_{tb}"]

    # Optional origin/destination markers. Coordinates may be WGS84 or raster CRS.
    projected_markers = []
    with rasterio.open(terrain_path) as marker_ds:
        for marker in markers or []:
            marker_crs = marker.get("crs", "EPSG:4326")
            mx, my = float(marker["x"]), float(marker["y"])
            if str(marker_crs) != str(marker_ds.crs):
                tx, ty = transform(marker_crs, marker_ds.crs, [mx], [my])
                mx, my = tx[0], ty[0]
            if marker_ds.bounds.left <= mx <= marker_ds.bounds.right and marker_ds.bounds.bottom <= my <= marker_ds.bounds.top:
                row, col = marker_ds.index(mx, my)
                row = min(max(row, 0), marker_ds.height - 1)
                col = min(max(col, 0), marker_ds.width - 1)
                elev = marker_ds.read(_band_index(marker_ds, "terrain_elevation_m"),
                                      window=rasterio.windows.Window(col, row, 1, 1))[0, 0]
                if marker_ds.nodata is not None and np.isclose(elev, marker_ds.nodata):
                    elev = float(np.nanmedian(dem))
                projected_markers.append({
                    "name": marker.get("name", "Point"),
                    "x": mx, "y": my, "z": float(elev) + float(marker.get("z_offset", 35.0)),
                    "symbol": marker.get("symbol", "diamond"),
                    "size": marker.get("size", 8),
                    "color": marker.get("color", "red"),
                })

    # Exact WGS 84 region geometry and endpoint markers from region_v1.geojson.
    # The boundary is clipped to the current raster footprint before plotting. This
    # prevents a full-region boundary from expanding the axes of route-corridor or
    # per-mosaic plots and creating large blank margins around the actual surface.
    projected_region_rings = []
    if region_spec is not None:
        with rasterio.open(terrain_path) as region_ds:
            transformer = Transformer.from_crs("EPSG:4326", region_ds.crs, always_xy=True)
            projected_geometry = shapely_transform(transformer.transform, shapely_shape(region_spec.geometry))
            clipped_geometry = projected_geometry.intersection(shapely_box(*region_ds.bounds))

            def _iter_exterior_rings(geometry):
                if geometry.is_empty:
                    return
                if geometry.geom_type == "Polygon":
                    yield list(geometry.exterior.coords)
                elif geometry.geom_type == "MultiPolygon":
                    for polygon in geometry.geoms:
                        yield list(polygon.exterior.coords)
                elif geometry.geom_type == "GeometryCollection":
                    for part in geometry.geoms:
                        yield from _iter_exterior_rings(part)

            for ring in _iter_exterior_rings(clipped_geometry) or []:
                rx = [float(p[0]) for p in ring]
                ry = [float(p[1]) for p in ring]
                rz = []
                for x0, y0 in zip(rx, ry):
                    try:
                        val = next(region_ds.sample([(x0, y0)], indexes=_band_index(region_ds, "terrain_elevation_m")))[0]
                        if region_ds.nodata is not None and np.isclose(val, region_ds.nodata):
                            val = np.nan
                    except Exception:
                        val = np.nan
                    rz.append(float(val) + 25.0 if np.isfinite(val) else float(np.nanmedian(dem)) + 25.0)
                projected_region_rings.append({"x": rx, "y": ry, "z": rz})
        existing_names = {str(m.get("name", "")).lower() for m in (markers or [])}
        exact_markers = []
        if region_spec.origin is not None and "origin" not in existing_names:
            exact_markers.append({"name": "Origin", "x": region_spec.origin[0], "y": region_spec.origin[1],
                                  "crs": "EPSG:4326", "color": "lime", "symbol": "diamond", "size": 9})
        if region_spec.destination is not None and "destination" not in existing_names:
            exact_markers.append({"name": "Destination", "x": region_spec.destination[0], "y": region_spec.destination[1],
                                  "crs": "EPSG:4326", "color": "red", "symbol": "diamond", "size": 9})
        if exact_markers:
            with rasterio.open(terrain_path) as marker_ds:
                for marker in exact_markers:
                    mx, my = transform("EPSG:4326", marker_ds.crs, [marker["x"]], [marker["y"]])
                    mx, my = mx[0], my[0]
                    if marker_ds.bounds.left <= mx <= marker_ds.bounds.right and marker_ds.bounds.bottom <= my <= marker_ds.bounds.top:
                        value = next(marker_ds.sample([(mx, my)], indexes=_band_index(marker_ds, "terrain_elevation_m")))[0]
                        if marker_ds.nodata is not None and np.isclose(value, marker_ds.nodata):
                            value = np.nanmedian(dem)
                        projected_markers.append({**marker, "x": mx, "y": my, "z": float(value) + 35.0})

    building_top = np.where(building_mask > 0, dem + building_height, np.nan)

    # marker overlays (light subsampling)
    marker_stride = max(1, step * 2)
    road_mask = roads[::marker_stride, ::marker_stride] > 0
    nat_mask = natural_obs[::marker_stride, ::marker_stride] > 0
    art_mask = artificial_obs[::marker_stride, ::marker_stride] > 0

    x_mark = xg[::marker_stride, ::marker_stride]
    y_mark = yg[::marker_stride, ::marker_stride]
    dem_mark = dem[::marker_stride, ::marker_stride]
    road_vals = roads[::marker_stride, ::marker_stride]
    nat_vals = natural_obs[::marker_stride, ::marker_stride]
    art_vals = artificial_obs[::marker_stride, ::marker_stride]

    # wind cones: stronger downsampling for performance
    cone_stride = max(2, step * 4)
    xc = xg[::cone_stride, ::cone_stride]
    yc = yg[::cone_stride, ::cone_stride]
    zc = dem[::cone_stride, ::cone_stride] + np.nan_to_num(building_height[::cone_stride, ::cone_stride]) * 0.3 + 40.0
    uc = wind_u[::cone_stride, ::cone_stride]
    vc = wind_v[::cone_stride, ::cone_stride]
    wc = np.zeros_like(uc)

    # 1) terrain & obstacles figure
    fig1 = go.Figure()
    fig1.add_trace(go.Surface(
        x=xg, y=yg, z=dem,
        surfacecolor=slope,
        colorscale="Earth",
        colorbar=dict(title="Slope (deg)"),
        name="Terrain",
        hovertemplate="X=%{x:.1f}<br>Y=%{y:.1f}<br>Terrain z=%{z:.1f} m<br>Slope=%{surfacecolor:.1f}°<extra></extra>",
    ))
    fig1.add_trace(go.Surface(
        x=xg, y=yg, z=building_top,
        surfacecolor=building_height,
        colorscale="Greys",
        showscale=False,
        opacity=0.95,
        name="Buildings",
        hovertemplate="Building top z=%{z:.1f} m<br>Building height=%{surfacecolor:.1f} m<extra></extra>",
    ))
    if road_mask.any():
        fig1.add_trace(go.Scatter3d(
            x=x_mark[road_mask], y=y_mark[road_mask], z=dem_mark[road_mask] + 2.0,
            mode="markers",
            marker=dict(size=2.5, color=road_vals[road_mask], colorscale="Turbo", opacity=0.7, colorbar=dict(title="Road class")),
            name="Road cells",
            hovertemplate="Road class=%{marker.color}<extra></extra>",
        ))
    if nat_mask.any():
        fig1.add_trace(go.Scatter3d(
            x=x_mark[nat_mask], y=y_mark[nat_mask], z=dem_mark[nat_mask] + 6.0,
            mode="markers",
            marker=dict(size=3.5, color=nat_vals[nat_mask], colorscale="Viridis", opacity=0.75),
            name="Natural obstacles",
            hovertemplate="Natural obstacle class=%{marker.color}<extra></extra>",
        ))
    if art_mask.any():
        fig1.add_trace(go.Scatter3d(
            x=x_mark[art_mask], y=y_mark[art_mask], z=dem_mark[art_mask] + 10.0,
            mode="markers",
            marker=dict(size=4.0, color=art_vals[art_mask], colorscale="Magma", opacity=0.85),
            name="Artificial obstacles",
            hovertemplate="Artificial obstacle class=%{marker.color}<extra></extra>",
        ))
    for marker in projected_markers:
        fig1.add_trace(go.Scatter3d(
            x=[marker["x"]], y=[marker["y"]], z=[marker["z"]],
            mode="markers+text", text=[marker["name"]], textposition="top center",
            marker=dict(size=marker["size"], color=marker["color"],
                        symbol=marker["symbol"], line=dict(width=2, color="black")),
            name=marker["name"],
            hovertemplate=f'{marker["name"]}<br>X=%{{x:.1f}}<br>Y=%{{y:.1f}}<br>Z=%{{z:.1f}} m<extra></extra>',
        ))

    for ring in projected_region_rings:
        fig1.add_trace(go.Scatter3d(
            x=ring["x"], y=ring["y"], z=ring["z"], mode="lines",
            line=dict(color="cyan", width=7), name="GeoJSON region boundary",
            hovertemplate="Exact region_v1.geojson boundary<extra></extra>"))

    fig1.update_layout(
        title=f"3D Terrain, Buildings, Roads and Obstacles ({tb} UTC)",
        scene=dict(
            xaxis_title="Projected X (m)",
            yaxis_title="Projected Y (m)",
            zaxis_title="Elevation / Height (m)",
            aspectmode="data",
        ),
        legend=dict(orientation="h"),
        margin=dict(l=0, r=0, b=0, t=40),
    )
    terrain_html = outdir / f"{prefix}_terrain_obstacles_3d.html"
    fig1.write_html(terrain_html, include_plotlyjs="cdn")

    # 2) climate dashboard figure
    fig2 = make_subplots(
        rows=2, cols=2,
        specs=[[{"type": "scene"}, {"type": "scene"}], [{"type": "scene"}, {"type": "scene"}]],
        subplot_titles=(
            f"Temperature ({tb})",
            f"Relative humidity ({tb})",
            f"Wind speed ({tb}) + direction cones",
            f"Wind direction ({tb}) / climate cluster",
        ),
    )
    fig2.add_trace(go.Surface(
        x=xg, y=yg, z=dem, surfacecolor=temp, colorscale="RdYlBu_r",
        colorbar=dict(title="°C", x=0.45), showscale=True, name="Temperature",
        hovertemplate="Terrain=%{z:.1f} m<br>Temp=%{surfacecolor:.2f} °C<extra></extra>",
    ), row=1, col=1)
    fig2.add_trace(go.Surface(
        x=xg, y=yg, z=dem, surfacecolor=rh, colorscale="Blues",
        colorbar=dict(title="RH %", x=1.02), showscale=True, name="Humidity",
        hovertemplate="Terrain=%{z:.1f} m<br>RH=%{surfacecolor:.2f} %<extra></extra>",
    ), row=1, col=2)
    fig2.add_trace(go.Surface(
        x=xg, y=yg, z=dem, surfacecolor=wind_speed, colorscale="Plasma",
        colorbar=dict(title="m/s", x=0.45, y=0.23), showscale=True, name="Wind speed",
        hovertemplate="Terrain=%{z:.1f} m<br>Wind speed=%{surfacecolor:.2f} m/s<extra></extra>",
    ), row=2, col=1)
    fig2.add_trace(go.Cone(
        x=xc.flatten(), y=yc.flatten(), z=zc.flatten(),
        u=uc.flatten(), v=vc.flatten(), w=wc.flatten(),
        sizemode="absolute", sizeref=max(np.nanmax(wind_speed), 1.0) / 8.0,
        anchor="tail", colorscale="Greys", showscale=False, name="Wind direction",
        hovertemplate="u=%{u:.2f} m/s<br>v=%{v:.2f} m/s<extra></extra>",
    ), row=2, col=1)
    fig2.add_trace(go.Surface(
        x=xg, y=yg, z=dem,
        surfacecolor=wind_dir,
        colorscale="HSV",
        cmin=0, cmax=360,
        colorbar=dict(title="Dir °", x=1.02, y=0.23), showscale=True,
        name="Wind direction",
        hovertemplate="Terrain=%{z:.1f} m<br>Wind dir=%{surfacecolor:.1f}°<extra></extra>",
    ), row=2, col=2)
    fig2.add_trace(go.Surface(
        x=xg, y=yg, z=dem + 15.0,
        surfacecolor=cluster_id,
        colorscale="Turbo",
        opacity=0.55,
        showscale=False,
        name="Climate cluster",
        hovertemplate="Cluster=%{surfacecolor:.0f}<extra></extra>",
    ), row=2, col=2)
    fig2.add_trace(go.Surface(
        x=xg, y=yg, z=dem + 30.0,
        surfacecolor=cluster_conf,
        colorscale="Viridis",
        opacity=0.35,
        colorbar=dict(title="Confidence", x=1.02, y=0.02),
        name="Cluster confidence",
        hovertemplate="Confidence=%{surfacecolor:.3f}<extra></extra>",
    ), row=2, col=2)

    for marker in projected_markers:
        for row, col in ((1, 1), (1, 2), (2, 1), (2, 2)):
            fig2.add_trace(go.Scatter3d(
                x=[marker["x"]], y=[marker["y"]], z=[marker["z"]],
                mode="markers+text", text=[marker["name"]], textposition="top center",
                marker=dict(size=marker["size"], color=marker["color"],
                            symbol=marker["symbol"], line=dict(width=2, color="black")),
                name=marker["name"], showlegend=(row == 1 and col == 1),
                hovertemplate=f'{marker["name"]}<br>X=%{{x:.1f}}<br>Y=%{{y:.1f}}<br>Z=%{{z:.1f}} m<extra></extra>',
            ), row=row, col=col)

    for scene_index in range(1, 5):
        row = (scene_index - 1) // 2 + 1
