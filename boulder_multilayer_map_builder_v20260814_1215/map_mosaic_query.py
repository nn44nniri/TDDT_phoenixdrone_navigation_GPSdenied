def mosaic3d(terrain_patterns, climate_patterns, bounds, hour, output_dir, magnetic_patterns=None,
             prefix="mosaic", max_grid=180, bounds_crs="EPSG:4326", region_spec=None):
    # Build bounded terrain/climate mosaics and render the extracted region in 3D.
    if hour is None:
        raise ValueError("mosaic3d requires --hour to select a climate time bin.")

    terrain_files = expand(terrain_patterns)
    climate_files = expand(climate_patterns)
    magnetic_files = expand(magnetic_patterns) if magnetic_patterns else []
    _validate_mosaic_sources(terrain_files, "terrain")
    _validate_mosaic_sources(climate_files, "climate")
    if magnetic_files:
        _validate_mosaic_sources(magnetic_files, "magnetic")

    coverage_validation = None
    if region_spec is not None:
        with rasterio.open(terrain_files[0]) as ds0:
            target_crs = ds0.crs
            requested_projected = _region_projected_bounds(region_spec, target_crs)
            tolerance = max(2.0 * abs(ds0.transform.a), 2.0 * abs(ds0.transform.e), 1.0)
        coverage_validation = {
            "requested_bounds_projected": list(requested_projected),
            "terrain": list(_require_complete_bounds(terrain_files, requested_projected, target_crs, "terrain", tolerance)),
            "climate": list(_require_complete_bounds(climate_files, requested_projected, target_crs, "climate", tolerance)),
            "magnetic": list(_require_complete_bounds(magnetic_files, requested_projected, target_crs, "magnetic", tolerance)) if magnetic_files else None,
        }

    outdir = Path(output_dir)
    outdir.mkdir(parents=True, exist_ok=True)
    prefix = _safe_name(prefix)
    terrain_output = outdir / f"{prefix}_terrain_mosaic.tif"
    climate_output = outdir / f"{prefix}_climate_mosaic.tif"
    magnetic_output = outdir / f"{prefix}_magnetic_mosaic.tif"

    print("[1/4] Extracting terrain mosaic for requested dimensions...", flush=True)
    terrain_meta = _mosaic_to_file(
        terrain_files, terrain_output, bounds=bounds, bounds_crs=bounds_crs
    )
    print("[2/4] Extracting climate mosaic for requested dimensions...", flush=True)
    climate_meta = _mosaic_to_file(
        climate_files, climate_output, bounds=bounds, bounds_crs=bounds_crs
    )
    magnetic_meta = None
    if magnetic_files:
        magnetic_meta = _mosaic_to_file(
            magnetic_files, magnetic_output, bounds=bounds, bounds_crs=bounds_crs
        )

    if terrain_meta["crs"] != climate_meta["crs"]:
        raise ValueError("Terrain and climate mosaics must have the same CRS for 3D rendering.")

    print("[3/4] Generating interactive Plotly 3D graphs...", flush=True)
    plot_info = generate_3d_plots(
        terrain_path=str(terrain_output),
        climate_path=str(climate_output),
        hour=hour,
        outdir=outdir,
        prefix=prefix,
        max_grid=max_grid,
        magnetic_path=str(magnetic_output) if magnetic_files else None,
        region_spec=region_spec,
    )

    manifest = {
        "command": "mosaic3d",
        "region_geojson": region_spec.provenance() if region_spec is not None else None,
        "region_coverage_validation": coverage_validation,
        "requested_bounds": list(bounds) if bounds is not None else None,
        "requested_bounds_crs": bounds_crs,
        "hour_utc": hour,
        "time_bin_utc": time_bin(hour),
        "terrain_inputs": [str(Path(f).resolve()) for f in terrain_files],
        "climate_inputs": [str(Path(f).resolve()) for f in climate_files],
        "magnetic_inputs": [str(Path(f).resolve()) for f in magnetic_files],
        "terrain_mosaic": terrain_meta,
        "climate_mosaic": climate_meta,
        "magnetic_mosaic": magnetic_meta,
        "plot_outputs": plot_info,
        "max_plot_grid": max_grid,
    }
    manifest_path = outdir / f"{prefix}_mosaic_3d_manifest.json"
    manifest_path.write_text(
        json.dumps(sanitize_for_json(manifest), indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    index_path = _write_plot_index(
        outdir,
        f"3D mosaic: {prefix}",
        [
            ("Terrain and obstacles 3D", plot_info["terrain_plot_html"]),
            ("Climate dashboard 3D", plot_info["climate_plot_html"]),
            *([("Magnetic anomaly 3D", plot_info["magnetic_plot_html"]),
               ("Extracted magnetic mosaic GeoTIFF", magnetic_output)] if magnetic_files else []),
            ("Extracted terrain mosaic GeoTIFF", terrain_output),
            ("Extracted climate mosaic GeoTIFF", climate_output),
            ("Mosaic manifest JSON", manifest_path),
            ("Plot summary JSON", plot_info["summary_json"]),
        ],
    )
    manifest["index_html"] = str(index_path.resolve())
    manifest_path.write_text(
        json.dumps(sanitize_for_json(manifest), indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    print("[4/4] Mosaic extraction and 3D rendering completed.", flush=True)
    print(json.dumps(sanitize_for_json(manifest), indent=2, ensure_ascii=False))


def _coverage_bounds(files, target_crs):
    bounds = []
    for file in files:
        with rasterio.open(file) as ds:
            bounds.append(transform_bounds(ds.crs, target_crs, *ds.bounds, densify_pts=21))
    return (
        min(b[0] for b in bounds), min(b[1] for b in bounds),
        max(b[2] for b in bounds), max(b[3] for b in bounds),
    )


def _require_complete_bounds(files, requested_bounds, target_crs, label, tolerance=1.0):
    coverage = _coverage_bounds(files, target_crs)
    rb = tuple(float(v) for v in requested_bounds)
    if (rb[0] < coverage[0] - tolerance or rb[1] < coverage[1] - tolerance or
            rb[2] > coverage[2] + tolerance or rb[3] > coverage[3] + tolerance):
        raise ValueError(
            f"The available {label} dataset does not cover the complete requested GeoJSON region. "
            f"available={coverage}, requested={rb}. Re-run build_regional_map.py "
            "with the same --region-file before generating reports."
        )
    return coverage



def _mask_raster_to_region(path, region_spec):
    """Mask a raster to the exact WGS84 Polygon/MultiPolygon from the region file."""
    if region_spec is None:
        return
    path = Path(path)
    with rasterio.open(path, "r+") as ds:
        transformer = Transformer.from_crs("EPSG:4326", ds.crs, always_xy=True)
        projected = shapely_transform(transformer.transform, shapely_shape(region_spec.geometry))
        inside = geometry_mask(
            [projected.__geo_interface__], out_shape=(ds.height, ds.width),
            transform=ds.transform, invert=True, all_touched=False,
        )
        nodata = ds.nodata
        if nodata is None:
            nodata = -9999.0 if np.issubdtype(np.dtype(ds.dtypes[0]), np.floating) else 0
            ds.nodata = nodata
        for band in range(1, ds.count + 1):
            arr = ds.read(band)
            arr[~inside] = nodata
            ds.write(arr, band)


def _copy_aligned_window(source_path, output_path, window):
    """Copy an exact pixel-aligned window while preserving band metadata."""
    source_path = Path(source_path)
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with rasterio.open(source_path) as src:
        window = window.round_offsets().round_lengths()
        if window.width < 1 or window.height < 1:
            raise ValueError(f"Empty aligned mosaic window: {window}")
        arr = src.read(window=window)
        transform_out = src.window_transform(window)
        profile = src.profile.copy()
        width = int(window.width)
        height = int(window.height)
        block_x = max(16, (min(256, width) // 16) * 16)
        block_y = max(16, (min(256, height) // 16) * 16)
        profile.update(
            width=width, height=height, transform=transform_out, tiled=True,
            blockxsize=block_x, blockysize=block_y, compress="DEFLATE", BIGTIFF="IF_SAFER",
        )
        with rasterio.open(output_path, "w", **profile) as dst:
            dst.write(arr)
            for i, desc in enumerate(src.descriptions, start=1):
                if desc:
                    dst.set_band_description(i, desc)
            dst.update_tags(**src.tags())
            for i in range(1, src.count + 1):
                tags = src.tags(i)
                if tags:
                    dst.update_tags(i, **tags)
    with rasterio.open(output_path) as ds:
        return {
            "output": str(output_path.resolve()),
            "shape": [ds.count, ds.height, ds.width],
            "crs": str(ds.crs),
            "bounds_projected": list(ds.bounds),
            "bounds_wgs84": list(transform_bounds(ds.crs, "EPSG:4326", *ds.bounds, densify_pts=21)),
            "resolution": [abs(ds.transform.a), abs(ds.transform.e)],
            "bands": list(band_map(ds).keys()),
            "grid_window": [int(window.col_off), int(window.row_off), int(window.width), int(window.height)],
        }


def _aligned_region_partitions(reference_path, origin_projected, destination_projected,
                               mosaic_count=None, mosaic_area_km2=None):
    """Partition the complete raster grid into gap-free, non-overlapping aligned tiles.

    Numbering follows the dominant origin-to-destination direction, while the union
    of all tile windows is exactly the complete reference raster.
    """
    if mosaic_count is not None and mosaic_area_km2 is not None:
        raise ValueError("Use either --mosaic-count or --mosaic-area-km2, not both.")
    with rasterio.open(reference_path) as ds:
        total_area_km2 = (ds.width * abs(ds.transform.a) * ds.height * abs(ds.transform.e)) / 1_000_000.0
        if mosaic_area_km2 is not None:
            if mosaic_area_km2 <= 0:
                raise ValueError("--mosaic-area-km2 must be positive.")
            mosaic_count = max(1, int(math.ceil(total_area_km2 / mosaic_area_km2)))
        if mosaic_count is None:
            mosaic_count = 4
        if mosaic_count < 1:
            raise ValueError("--mosaic-count must be at least 1.")

        ox, oy = origin_projected
        dx, dy = destination_projected
        split_axis = "columns" if abs(dx - ox) >= abs(dy - oy) else "rows"
        dimension = ds.width if split_axis == "columns" else ds.height
        if mosaic_count > dimension:
            raise ValueError(
                f"Requested {mosaic_count} mosaics but the raster has only {dimension} pixels "
                f"along the selected {split_axis} axis."
            )
        edges = np.rint(np.linspace(0, dimension, mosaic_count + 1)).astype(int)
        edges[0], edges[-1] = 0, dimension
        if np.any(np.diff(edges) <= 0):
            raise ValueError("Mosaic count produces an empty raster-aligned tile.")

        windows = []
        for a, b in zip(edges[:-1], edges[1:]):
            if split_axis == "columns":
                windows.append(Window(a, 0, b - a, ds.height))
            else:
                windows.append(Window(0, a, ds.width, b - a))

        # Raster rows increase southward. Order tiles from origin toward destination.
        if split_axis == "columns" and dx < ox:
            windows.reverse()
        elif split_axis == "rows" and dy > oy:
            windows.reverse()

        tiles = []
        for index, win in enumerate(windows, start=1):
            b = window_bounds(win, ds.transform)
            tiles.append({
                "index": index,
                "window": win,
                "grid_window": [int(win.col_off), int(win.row_off), int(win.width), int(win.height)],
                "bounds_projected": [float(v) for v in b],
                "bounds_wgs84": list(transform_bounds(ds.crs, "EPSG:4326", *b, densify_pts=21)),
                "nominal_area_km2": float(win.width * abs(ds.transform.a) * win.height * abs(ds.transform.e) / 1_000_000.0),
            })
        return {
            "mode": "complete_region_raster_aligned",
            "split_axis": split_axis,
            "mosaic_count": int(mosaic_count),
            "total_raster_area_km2": float(total_area_km2),
            "reference_shape": [ds.height, ds.width],
            "reference_transform": tuple(ds.transform),
            "reference_bounds_projected": list(ds.bounds),
            "tiles": tiles,
        }

def _route_tile_bounds(origin_lon, origin_lat, destination_lon, destination_lat,
                       raster_crs, corridor_width_m, mosaic_count=None,
                       mosaic_area_km2=None):
    if mosaic_count is not None and mosaic_area_km2 is not None:
        raise ValueError("Use either --mosaic-count or --mosaic-area-km2, not both.")
    if mosaic_count is None and mosaic_area_km2 is None:
        mosaic_count = 4
    if mosaic_count is not None and mosaic_count < 1:
        raise ValueError("--mosaic-count must be at least 1.")
    if mosaic_area_km2 is not None and mosaic_area_km2 <= 0:
        raise ValueError("--mosaic-area-km2 must be positive.")
    if corridor_width_m <= 0:
        raise ValueError("--corridor-width-m must be positive.")

    xs, ys = transform("EPSG:4326", raster_crs,
                       [origin_lon, destination_lon], [origin_lat, destination_lat])
    ox, dx = xs
    oy, dy = ys
    half = corridor_width_m / 2.0
    minx, maxx = min(ox, dx) - half, max(ox, dx) + half
    miny, maxy = min(oy, dy) - half, max(oy, dy) + half
    width = maxx - minx
    height = maxy - miny
    total_area_km2 = width * height / 1_000_000.0
    if mosaic_area_km2 is not None:
        mosaic_count = max(1, int(math.ceil(total_area_km2 / mosaic_area_km2)))

    tiles = []
    if width >= height:
        edges = np.linspace(minx, maxx, mosaic_count + 1)
        for i in range(mosaic_count):
            tiles.append((float(edges[i]), float(miny), float(edges[i+1]), float(maxy)))
    else:
        edges = np.linspace(miny, maxy, mosaic_count + 1)
        for i in range(mosaic_count):
            tiles.append((float(minx), float(edges[i]), float(maxx), float(edges[i+1])))
    return {
        "raster_crs": str(raster_crs),
        "origin_projected": [float(ox), float(oy)],
        "destination_projected": [float(dx), float(dy)],
        "corridor_bounds_projected": [float(minx), float(miny), float(maxx), float(maxy)],
        "corridor_area_km2": total_area_km2,
        "mosaic_count": int(mosaic_count),
        "nominal_area_per_mosaic_km2": total_area_km2 / mosaic_count,
        "tiles_projected": tiles,
    }


def _point_in_bounds(x, y, bounds):
    return bounds[0] <= x <= bounds[2] and bounds[1] <= y <= bounds[3]


def _region_projected_bounds(region_spec, raster_crs):
    """Return exact GeoJSON geometry bounds transformed to the raster CRS."""
    transformer = Transformer.from_crs("EPSG:4326", raster_crs, always_xy=True)
    geom = shapely_transform(transformer.transform, shapely_shape(region_spec.geometry))
    return tuple(float(v) for v in geom.bounds)


def _valid_fraction(path):
    """Fraction of valid cells in band 1, useful for output coverage diagnostics."""
    with rasterio.open(path) as ds:
        data = ds.read(1, masked=True)
        return float(data.count() / data.size) if data.size else 0.0


def _route_index(outdir, title, overall_links, tile_entries):
    overall = "\n".join(
        f'<li><a href="{Path(path).relative_to(outdir)}">{label}</a></li>'
        for label, path in overall_links
    )
    sections = []
    for entry in tile_entries:
        links = "\n".join(
            f'<li><a href="{Path(path).relative_to(outdir)}">{label}</a></li>'
            for label, path in entry["links"]
        )
        sections.append(f'<h2>Mosaic {entry["index"]:03d}</h2><ul>{links}</ul>')
    html = (
        '<!doctype html><html><head><meta charset="utf-8">'
        f'<title>{title}</title>'
        '<style>body{font-family:Arial,sans-serif;max-width:1050px;margin:2rem auto;line-height:1.5}'
        'li{margin:.45rem 0}h2{border-top:1px solid #ccc;padding-top:1rem}</style></head>'
        f'<body><h1>{title}</h1><h2>Overall requested region</h2><ul>{overall}</ul>'
        f'{"".join(sections)}</body></html>'
    )
    path = Path(outdir) / "route_3d_index.html"
    path.write_text(html, encoding="utf-8")
    return path


def route3d(terrain_patterns, climate_patterns, origin, destination, hour,
            output_dir, prefix="route", mosaic_count=None, mosaic_area_km2=None,
            corridor_width_m=500.0, max_grid=180, magnetic_patterns=None, region_spec=None):
    if hour is None:
        raise ValueError("route3d requires --hour.")
    terrain_files = expand(terrain_patterns)
    climate_files = expand(climate_patterns)
    magnetic_files = expand(magnetic_patterns) if magnetic_patterns else []
    terrain_signature = _validate_mosaic_sources(terrain_files, "terrain")
    climate_signature = _validate_mosaic_sources(climate_files, "climate")
    if terrain_signature["crs"] != climate_signature["crs"]:
        raise ValueError("Terrain and climate source mosaics must use the same CRS.")
    if magnetic_files:
        magnetic_signature = _validate_mosaic_sources(magnetic_files, "magnetic")
        if terrain_signature["crs"] != magnetic_signature["crs"]:
            raise ValueError("Terrain and magnetic source mosaics must use the same CRS.")
    raster_crs = terrain_signature["crs"]

    origin_lon, origin_lat = origin
    destination_lon, destination_lat = destination
    route = _route_tile_bounds(
        origin_lon, origin_lat, destination_lon, destination_lat,
        raster_crs, corridor_width_m, mosaic_count, mosaic_area_km2,
    )
    terrain_coverage = _coverage_bounds(terrain_files, raster_crs)
    climate_coverage = _coverage_bounds(climate_files, raster_crs)
    magnetic_coverage = _coverage_bounds(magnetic_files, raster_crs) if magnetic_files else None
    cb = route["corridor_bounds_projected"]
    _require_complete_bounds(terrain_files, cb, raster_crs, "terrain")
    _require_complete_bounds(climate_files, cb, raster_crs, "climate")
    if magnetic_files:
        _require_complete_bounds(magnetic_files, cb, raster_crs, "magnetic")
    coverage = terrain_coverage

    # With a region GeoJSON, the overall report must represent the complete
    # requested region rather than only the smaller origin-destination corridor.
    # Per-mosaic products remain route partitions, preserving previous behavior.
    overall_bounds = tuple(cb)
    overall_scope = "route_corridor"
    if region_spec is not None:
        overall_bounds = _region_projected_bounds(region_spec, raster_crs)
        with rasterio.open(terrain_files[0]) as ds0:
            tolerance = max(2.0 * abs(ds0.transform.a), 2.0 * abs(ds0.transform.e), 1.0)
        _require_complete_bounds(terrain_files, overall_bounds, raster_crs, "terrain", tolerance)
        _require_complete_bounds(climate_files, overall_bounds, raster_crs, "climate", tolerance)
        if magnetic_files:
            _require_complete_bounds(magnetic_files, overall_bounds, raster_crs, "magnetic", tolerance)
        overall_scope = "complete_geojson_region"

    outdir = Path(output_dir)
    outdir.mkdir(parents=True, exist_ok=True)
    prefix = _safe_name(prefix)
    markers = [
        {"name": "Origin", "x": origin_lon, "y": origin_lat, "crs": "EPSG:4326",
         "color": "lime", "symbol": "diamond", "size": 9},
        {"name": "Destination", "x": destination_lon, "y": destination_lat, "crs": "EPSG:4326",
         "color": "red", "symbol": "diamond", "size": 9},
    ]

    print(f"[1/{route['mosaic_count'] + 3}] Building complete overall region...", flush=True)
    overall_dir = outdir / "overall_route"
    overall_dir.mkdir(exist_ok=True)
    overall_terrain = overall_dir / f"{prefix}_overall_terrain.tif"
    overall_climate = overall_dir / f"{prefix}_overall_climate.tif"
    overall_magnetic = overall_dir / f"{prefix}_overall_magnetic.tif"
    overall_terrain_meta = _mosaic_to_file(
        terrain_files, overall_terrain, bounds=overall_bounds, bounds_crs=raster_crs)
    overall_climate_meta = _mosaic_to_file(
        climate_files, overall_climate, bounds=overall_bounds, bounds_crs=raster_crs)
    overall_magnetic_meta = None
    if magnetic_files:
        overall_magnetic_meta = _mosaic_to_file(
            magnetic_files, overall_magnetic, bounds=overall_bounds, bounds_crs=raster_crs)

    # Enforce the exact GeoJSON polygon on the overall products. This also makes
    # the overall raster the authoritative grid from which region mosaics are cut.
    if region_spec is not None:
        _mask_raster_to_region(overall_terrain, region_spec)
        _mask_raster_to_region(overall_climate, region_spec)
        if magnetic_files:
            _mask_raster_to_region(overall_magnetic, region_spec)
        # Refresh metadata after masking (bounds/grid stay identical).
        with rasterio.open(overall_terrain) as ds:
            overall_terrain_meta["valid_fraction_band1"] = _valid_fraction(overall_terrain)
        with rasterio.open(overall_climate) as ds:
            overall_climate_meta["valid_fraction_band1"] = _valid_fraction(overall_climate)
        if magnetic_files:
            overall_magnetic_meta["valid_fraction_band1"] = _valid_fraction(overall_magnetic)

    overall_plots = generate_3d_plots(
        str(overall_terrain), str(overall_climate), hour, overall_dir,
        f"{prefix}_overall", max_grid=max_grid, markers=markers,
        magnetic_path=str(overall_magnetic) if magnetic_files else None, region_spec=region_spec)

    tile_reports = []
    tile_index_entries = []
    ox, oy = route["origin_projected"]
    dx, dy = route["destination_projected"]

    # When a GeoJSON region is supplied, mosaics are exact, gap-free partitions
    # of the complete overall raster—not partitions of the smaller route corridor.
    # This guarantees that their union equals the full region raster grid and that
    # terrain, climate and magnetic tiles share identical windows/transforms.
    aligned_partition = None
    if region_spec is not None:
        aligned_partition = _aligned_region_partitions(
            overall_terrain, (ox, oy), (dx, dy),
            mosaic_count=mosaic_count, mosaic_area_km2=mosaic_area_km2,
        )
        route["partition_mode"] = aligned_partition["mode"]
        route["split_axis"] = aligned_partition["split_axis"]
        route["mosaic_count"] = aligned_partition["mosaic_count"]
        route["complete_region_reference_shape"] = aligned_partition["reference_shape"]
        route["complete_region_reference_transform"] = aligned_partition["reference_transform"]
        route["complete_region_reference_bounds_projected"] = aligned_partition["reference_bounds_projected"]
        route["tiles_projected"] = [item["bounds_projected"] for item in aligned_partition["tiles"]]
        route["tiles_grid_windows"] = [item["grid_window"] for item in aligned_partition["tiles"]]
        tile_specs = aligned_partition["tiles"]
    else:
        route["partition_mode"] = "route_corridor_bounds"
        tile_specs = [
            {
                "index": i, "bounds_projected": list(bounds), "window": None,
                "grid_window": None,
                "bounds_wgs84": list(transform_bounds(raster_crs, "EPSG:4326", *bounds, densify_pts=21)),
                "nominal_area_km2": ((bounds[2]-bounds[0])*(bounds[3]-bounds[1]))/1_000_000.0,
            }
            for i, bounds in enumerate(route["tiles_projected"], start=1)
        ]

    for tile_spec in tile_specs:
        index = int(tile_spec["index"])
        bounds = tuple(tile_spec["bounds_projected"])
        print(f"[{index + 1}/{route['mosaic_count'] + 3}] Building route mosaic {index}/{route['mosaic_count']}...", flush=True)
        tile_dir = outdir / f"mosaic_{index:03d}"
        tile_dir.mkdir(exist_ok=True)
        tile_prefix = f"{prefix}_mosaic_{index:03d}"
        terrain_output = tile_dir / f"{tile_prefix}_terrain.tif"
        climate_output = tile_dir / f"{tile_prefix}_climate.tif"
        magnetic_output = tile_dir / f"{tile_prefix}_magnetic.tif"
        if region_spec is not None:
            window = tile_spec["window"]
            terrain_meta = _copy_aligned_window(overall_terrain, terrain_output, window)
            climate_meta = _copy_aligned_window(overall_climate, climate_output, window)
            magnetic_meta = None
            if magnetic_files:
                magnetic_meta = _copy_aligned_window(overall_magnetic, magnetic_output, window)
        else:
            terrain_meta = _mosaic_to_file(
                terrain_files, terrain_output, bounds=bounds, bounds_crs=raster_crs)
            climate_meta = _mosaic_to_file(
                climate_files, climate_output, bounds=bounds, bounds_crs=raster_crs)
            magnetic_meta = None
            if magnetic_files:
                magnetic_meta = _mosaic_to_file(
                    magnetic_files, magnetic_output, bounds=bounds, bounds_crs=raster_crs)

        tile_markers = []
        if _point_in_bounds(ox, oy, bounds):
            tile_markers.append(markers[0])
        if _point_in_bounds(dx, dy, bounds):
            tile_markers.append(markers[1])
        plots = generate_3d_plots(
            str(terrain_output), str(climate_output), hour, tile_dir,
            tile_prefix, max_grid=max_grid, markers=tile_markers,
            magnetic_path=str(magnetic_output) if magnetic_files else None, region_spec=region_spec)
        tile_report = {
            "index": index,
            "partition_mode": route.get("partition_mode"),
            "grid_window": tile_spec.get("grid_window"),
            "bounds_projected_requested": list(bounds),
            "bounds_wgs84_requested": list(tile_spec.get("bounds_wgs84") or transform_bounds(
                raster_crs, "EPSG:4326", *bounds, densify_pts=21)),
            "nominal_area_km2": float(tile_spec.get("nominal_area_km2", ((bounds[2]-bounds[0])*(bounds[3]-bounds[1]))/1_000_000.0)),
            "contains_origin": _point_in_bounds(ox, oy, bounds),
            "contains_destination": _point_in_bounds(dx, dy, bounds),
            "terrain": terrain_meta,
            "climate": climate_meta,
            "magnetic": magnetic_meta,
            "plots": plots,
        }
        report_path = tile_dir / f"{tile_prefix}_report.json"
        report_path.write_text(json.dumps(sanitize_for_json(tile_report), indent=2), encoding="utf-8")
        tile_report["report_json"] = str(report_path.resolve())
        tile_reports.append(tile_report)
        tile_index_entries.append({
            "index": index,
            "links": [
                ("Terrain and obstacles 3D", plots["terrain_plot_html"]),
                ("Climate dashboard 3D", plots["climate_plot_html"]),
                *([("Magnetic anomaly 3D", plots["magnetic_plot_html"])] if magnetic_files else []),
                ("Terrain GeoTIFF", terrain_output),
                ("Climate GeoTIFF", climate_output),
                *([("Magnetic GeoTIFF", magnetic_output)] if magnetic_files else []),
                ("Tile report JSON", report_path),
            ],
        })

    print(f"[{route['mosaic_count'] + 2}/{route['mosaic_count'] + 3}] Writing route manifest and index...", flush=True)
    geod = Geod(ellps="WGS84")
    azimuth, _, distance_m = geod.inv(origin_lon, origin_lat, destination_lon, destination_lat)
    mosaic_grid_validation = None
    if region_spec is not None and aligned_partition is not None:
        with rasterio.open(overall_terrain) as ref:
            total_pixels = sum(int(item["window"].width * item["window"].height) for item in aligned_partition["tiles"])
            mosaic_grid_validation = {
                "union_equals_complete_overall_raster": total_pixels == ref.width * ref.height,
                "overlap_pixels": 0,
                "gap_pixels": int(ref.width * ref.height - total_pixels),
                "overall_shape": [ref.height, ref.width],
                "sum_tile_pixels": int(total_pixels),
                "shared_crs": str(ref.crs),
                "shared_resolution": [abs(ref.transform.a), abs(ref.transform.e)],
            }

    manifest = {
        "command": "route3d",
        "region_geojson": region_spec.provenance() if region_spec is not None else None,
        "origin_wgs84": [origin_lon, origin_lat],
        "destination_wgs84": [destination_lon, destination_lat],
        "geodesic_distance_m": distance_m,
        "initial_azimuth_deg": azimuth % 360.0,
        "hour_utc": hour,
        "time_bin_utc": time_bin(hour),
        "corridor_width_m": corridor_width_m,
        "overall_scope": overall_scope,
        "overall_bounds_projected_requested": list(overall_bounds),
        "source_coverage_projected": {
            "terrain": list(terrain_coverage),
            "climate": list(climate_coverage),
            "magnetic": list(magnetic_coverage) if magnetic_coverage is not None else None,
        },
        "partition": route,
        "mosaic_grid_validation": mosaic_grid_validation,
        "magnetic_inputs": [str(Path(f).resolve()) for f in magnetic_files],
        "overall": {
            "terrain": overall_terrain_meta,
            "climate": overall_climate_meta,
            "magnetic": overall_magnetic_meta,
            "plots": overall_plots,
            "valid_fraction_band1": {
                "terrain": _valid_fraction(overall_terrain),
                "climate": _valid_fraction(overall_climate),
                "magnetic": _valid_fraction(overall_magnetic) if magnetic_files else None,
            },
        },
        "mosaics": tile_reports,
    }
    manifest_path = outdir / f"{prefix}_route_3d_manifest.json"
    manifest_path.write_text(json.dumps(sanitize_for_json(manifest), indent=2), encoding="utf-8")
    index_path = _route_index(
        outdir, f"3D route mosaics: {prefix}",
        [
            ("Overall terrain and obstacles 3D", overall_plots["terrain_plot_html"]),
            ("Overall climate dashboard 3D", overall_plots["climate_plot_html"]),
            *([("Overall magnetic anomaly 3D", overall_plots["magnetic_plot_html"])] if magnetic_files else []),
            ("Overall terrain GeoTIFF", overall_terrain),
            ("Overall climate GeoTIFF", overall_climate),
            *([("Overall magnetic GeoTIFF", overall_magnetic)] if magnetic_files else []),
            ("Route manifest JSON", manifest_path),
        ],
        tile_index_entries,
    )
    manifest["index_html"] = str(index_path.resolve())
    manifest_path.write_text(json.dumps(sanitize_for_json(manifest), indent=2), encoding="utf-8")
    print(f"[{route['mosaic_count'] + 3}/{route['mosaic_count'] + 3}] Route mosaics completed.", flush=True)
    print(json.dumps(sanitize_for_json(manifest), indent=2, ensure_ascii=False))


def do_mosaic(files, output, bounds_wgs84=None):
    sources = [rasterio.open(f) for f in files]
    try:
        bounds = None
        if bounds_wgs84:
            bounds = transform_bounds("EPSG:4326", sources[0].crs, *bounds_wgs84, densify_pts=21)
        arr, out_transform = merge(
            sources, bounds=bounds, method="first",
            target_aligned_pixels=True, mem_limit=128
        )
        profile = sources[0].profile.copy()
        bx = max(16, min(256, (arr.shape[2] // 16) * 16))
        by = max(16, min(256, (arr.shape[1] // 16) * 16))
        profile.update(
            driver="GTiff", height=arr.shape[1], width=arr.shape[2],
            transform=out_transform, count=arr.shape[0],
            tiled=True, blockxsize=bx, blockysize=by, compress="DEFLATE", BIGTIFF="IF_SAFER"
        )
        with rasterio.open(output, "w", **profile) as dst:
            dst.write(arr)
            for i, desc in enumerate(sources[0].descriptions, start=1):
                if desc:
                    dst.set_band_description(i, desc)
        print(json.dumps({"output": str(Path(output).resolve()), "shape": list(arr.shape)}, indent=2))
    finally:
        for src in sources:
            src.close()


