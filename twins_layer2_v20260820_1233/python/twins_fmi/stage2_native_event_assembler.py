"""Fail-closed assembler: independently logged native events -> paired JSONL.

No MAVLink-only path can supply measured motor omega or JSBSim truth.
Inputs must be generated by an independently instrumented FCU/JSBSim native
exporter.  No synthetic interpolation, implicit units, IDs, or predictions.
"""
from __future__ import annotations
import hashlib
import json
import math
from pathlib import Path
from typing import Any
from .native_actuator_binding import ActuatorReplaySample, NativeReplayRejected

REQUIRED_SAMPLE_SIGNALS={
    'left_motor_cmd':'1','right_motor_cmd':'1',
    'left_elevon_rad':'rad','right_elevon_rad':'rad',
    'omega_left':'rad/s','omega_right':'rad/s'
}
REQUIRED_OBS_SIGNALS={
    'vn':'m/s','ve':'m/s','vd':'m/s',
    'omega_left':'rad/s','omega_right':'rad/s'
}
BANNED=('pwm','stick','manual_control','rc_channels','pilot_throttle','synthetic',
        'prediction','wingmpet','surrogate','estimated_from_throttle')
ALLOWED_PRODUCERS={
    'NATIVE_JSBSIM_PROPERTY_LOG','NATIVE_FCU_POST_MIXER_LOG',
    'MERGED_NATIVE_FCU_JSBSIM_LOG','NATIVE_ESC_RPM_TELEMETRY_LOG'
}


def sha256(path):
    h=hashlib.sha256()
    with Path(path).open('rb') as f:
        for chunk in iter(lambda:f.read(1024*1024),b''):
            h.update(chunk)
    return h.hexdigest()


def check_evidence(ev:Any,kind:str)->dict:
    if not isinstance(ev,dict):
        raise NativeReplayRejected(f'{kind} independently sourced native evidence is required')
    producer=ev.get('producer')
    if producer not in ALLOWED_PRODUCERS:
        raise NativeReplayRejected(f'{kind} producer must be named native post-controller/JSBSim source')
    path=Path(ev.get('source_file') or '')
    if not path.is_file():
        raise NativeReplayRejected(f'{kind} source_file must exist on disk')
    digest=ev.get('source_sha256')
    if not isinstance(digest,str) or len(digest)!=64 or digest!=sha256(path):
        raise NativeReplayRejected(f'{kind} native source sha256 mismatch')
    signal_map=ev.get('signal_map')
    required=REQUIRED_SAMPLE_SIGNALS if kind=='sample' else REQUIRED_OBS_SIGNALS
    if not isinstance(signal_map,dict):
        raise NativeReplayRejected(f'{kind} independent signal map required')
    for name,unit in required.items():
        signal=signal_map.get(name)
        if not isinstance(signal,dict) or signal.get('unit')!=unit or not isinstance(signal.get('native_signal'),str):
            raise NativeReplayRejected(f'{kind}.{name}: native signal and exact unit {unit} required')
        s=signal['native_signal'].lower().strip()
        if not s or any(bad in s for bad in BANNED):
            raise NativeReplayRejected(f'{kind}.{name}: pilot/PWM/model proxy cannot replace measured actuator/omega')
    if ev.get('time_domain')!='JSBSIM_PLANT_SECONDS':
        raise NativeReplayRejected(f'{kind} time_domain must be native JSBSim plant seconds')
    if kind=='observation' and ev.get('velocity_frame')!='NED':
        raise NativeReplayRejected('observation velocity must be NED')
    return {'source_file':str(path.resolve()),'source_sha256':digest,
            'producer':producer,'time_domain':ev['time_domain'],
            'signal_map':{key:signal_map[key] for key in required},
            **({'velocity_frame':'NED'} if kind=='observation' else {})}


def assemble(events):
    samples={}; observations={}
    for line,event in enumerate(events,1):
        if not isinstance(event,dict) or event.get('kind') not in ('sample','observation'):
            raise NativeReplayRejected(f'line {line}: expected native sample/observation event')
        kind=event['kind']; payload=event.get(kind)
        if not isinstance(payload,dict):
            raise NativeReplayRejected(f'line {line}: {kind} must be an object')
        e=check_evidence(event.get('evidence'),kind)
        tx=payload.get('transaction_id'); snap=payload.get('snapshot_id')
        if not all(isinstance(x,str) and x.strip() for x in (tx,snap)):
            raise NativeReplayRejected(f'line {line}: transaction and snapshot required')
        key=(tx,snap)
        dst=samples if kind=='sample' else observations
        if key in dst:
            raise NativeReplayRejected(f'line {line}: duplicate {kind} for transaction/snapshot')
        dst[key]=(payload,e)
    if not samples or not observations or set(samples)!=set(observations):
        raise NativeReplayRejected('unmatched native sample/observation transactions: no partial pairs')
    result=[]
    for key in sorted(samples,key=lambda k:float(samples[k][0].get('plant_time_s',math.nan))):
        sample,sev=samples[key]; observation,oev=observations[key]
        u=ActuatorReplaySample.from_mapping(sample).validated()
        if observation.get('controller_identity')!=sample['controller_identity'] or observation.get('model_identity')!=sample['model_identity']:
            raise NativeReplayRejected('native sample/observation model identity mismatch')
        if observation.get('motor_state_source') not in ('jsbsim_property','motor_rpm_telemetry'):
            raise NativeReplayRejected('observation motor must be a native property or measured RPM telemetry')
        if sample.get('motor_state_source')=='dynamic_motor_estimator':
            raise NativeReplayRejected('native measured site comparison cannot use initial estimated omega')
        if sample['actuator_source'] not in ('jsbsim_actuator_property','fcu_servo_output_with_verified_mapping'):
            raise NativeReplayRejected('native actuator output required')
        start=float(sample['plant_time_s'])
        end=float(observation.get('plant_time_s',math.nan))
        if not(math.isfinite(end) and abs(end-start-u['dt']) <= .005):
            raise NativeReplayRejected('observation time must match same native segment, <=5ms skew')
        for n in REQUIRED_OBS_SIGNALS:
            if n not in observation or not math.isfinite(float(observation[n])):
                raise NativeReplayRejected(f'observation missing/nonfinite {n}')
        result.append({'sample':sample,'observation':observation,
                       'source_evidence':{'sample':sev,'observation':oev,
                            'pair_provenance':'INDEPENDENT_NATIVE_EXPORT_NOT_CONTROLLER_CERTIFICATION'}})
    if any(float(a['sample']['plant_time_s'])>=float(b['sample']['plant_time_s']) for a,b in zip(result,result[1:])):
        raise NativeReplayRejected('native sample plant time must be strictly increasing')
    return result


def read_events(path):
    with Path(path).open('r',encoding='utf-8') as f:
        for line_num,txt in enumerate(f,1):
            if txt.strip():
                try: yield json.loads(txt)
                except ValueError as e:
                    raise NativeReplayRejected(f'line {line_num}: invalid JSON') from e
