PARAM_TEMPLATE = """# Generated by phoenix-environment-adapter\nQ_ENABLE 1\nQ_TAILSIT_ENABLE 1\nQ_FRAME_CLASS 10\nQ_TAILSIT_MOTMX 0\nSERVO1_FUNCTION 77\nSERVO2_FUNCTION 78\nSERVO3_FUNCTION 73\nSERVO4_FUNCTION 74\nSERVO1_MIN 1000\nSERVO1_TRIM 1500\nSERVO1_MAX 2000\nSERVO2_MIN 1000\nSERVO2_TRIM 1500\nSERVO2_MAX 2000\nSERVO3_MIN 1000\nSERVO3_TRIM 1000\nSERVO3_MAX 2000\nSERVO4_MIN 1000\nSERVO4_TRIM 1000\nSERVO4_MAX 2000\nRUDD_DT_GAIN 0\nAHRS_EKF_TYPE 10\nARSPD_TYPE 100\nBATT_MONITOR 4\nBATT_CAPACITY 2200\nTERRAIN_ENABLE 0\nTERRAIN_FOLLOW 0\nSIM_WIND_SPD {wind_speed:.6f}\nSIM_WIND_DIR {wind_dir:.6f}\nSIM_WIND_TURB 0.0\n"""

def bearing_deg(lat1, lon1, lat2, lon2):
    p1,p2=math.radians(lat1),math.radians(lat2); dl=math.radians(lon2-lon1)
    y=math.sin(dl)*math.cos(p2); x=math.cos(p1)*math.sin(p2)-math.sin(p1)*math.cos(p2)*math.cos(dl)
    return (math.degrees(math.atan2(y,x))+360)%360

def prepare(dataset_tar, region_path, vehicle_path, timestamp, output_dir, cache_dir=None):
    out = Path(output_dir); out.mkdir(parents=True, exist_ok=True)
    cache = Path(cache_dir) if cache_dir else out / "dataset_cache"
    ds = DatasetLayout.from_tar(dataset_tar, cache); meta=ds.validate()
    region=Region(region_path); terrain=TerrainProvider(meta["dem_path"]); climate=ClimateProvider(ds.climate_dir)
    dt = datetime.fromisoformat(timestamp.replace("Z","+00:00")).astimezone(timezone.utc)
    hs=terrain.elevation_msl(region.start.lat, region.start.lon)
    hd=terrain.elevation_msl(region.destination.lat, region.destination.lon)
    cs=climate.sample(region.start.lat, region.start.lon, dt)
    heading=bearing_deg(region.start.lat,region.start.lon,region.destination.lat,region.destination.lon)
    vehicle=PhoenixVehicle(vehicle_path)
    aligned_vehicle=vehicle.ground_vtol_copy(hs)
    cg_agl=aligned_vehicle['simulation_assumptions']['initial_agl_m']
    vehicle.write_ground_vtol(out/"phoenix_drone_v3_ground_vtol.yaml", hs)
    (out/"phoenix_tailsitter.parm").write_text(PARAM_TEMPLATE.format(wind_speed=cs.wind_speed_m_s, wind_dir=cs.wind_direction_from_deg))
    (out/"locations.txt.fragment").write_text(f"PhoenixBoulder={region.start.lat:.8f},{region.start.lon:.8f},{hs:.2f},{heading:.1f}\n")
    runtime={
      "schema_version":"1.0",
      "simulation_time_utc":dt.isoformat(),
      "region":{"name":region.name,"bbox":region.bbox},
      "home":{"lat":region.start.lat,"lon":region.start.lon,"terrain_msl_m":hs,"initial_agl_m":cg_agl,"initial_CG_msl_m":hs+cg_agl,"position_origin":"CG","heading_deg":heading},
      "destination":{"lat":region.destination.lat,"lon":region.destination.lon,"terrain_msl_m":hd},
      "climate_at_home":{"temperature_c":cs.temperature_c,"relative_humidity_pct":cs.relative_humidity_pct,
                         "wind_speed_m_s":cs.wind_speed_m_s,"wind_direction_from_deg":cs.wind_direction_from_deg,
                         "wind_north_m_s":cs.wind_north_m_s,"wind_east_m_s":cs.wind_east_m_s},
      "vehicle":{"model":"Phoenix","type":"dual_rotor_tailsitter","forward_flight_air_start_only":False},
      "embedded_jsbsim":{"mode":"ArduPilot SIM_JSBSim child process","wind_path":"Adapter -> MAVLink SIM_WIND_* -> SITL input.wind -> SIM_JSBSim.cpp -> JSBSim atmosphere properties",
                         "direct_control_socket_connection":False,
                         "terrain_injection":"not performed in no-patch mode; DEM is mission/safety/home truth",
                         "temperature_humidity_injection":"not performed by current ArduPilot SIM_JSBSim backend; retained in runtime_environment.json"}
    }
    (out/"runtime_environment.json").write_text(json.dumps(runtime,indent=2))
    # Simple QGC WPL mission: VTOL takeoff 40m, destination approach 50m relative, VTOL land.
    # This is a seed only; terrain-aware path planning should add intermediate waypoints.
    lines=["QGC WPL 110",
      f"0\t1\t0\t16\t0\t0\t0\t0\t{region.start.lat:.8f}\t{region.start.lon:.8f}\t0\t1",
      f"1\t0\t3\t84\t0\t0\t0\t0\t{region.start.lat:.8f}\t{region.start.lon:.8f}\t40\t1",
      f"2\t0\t3\t16\t0\t0\t0\t0\t{region.destination.lat:.8f}\t{region.destination.lon:.8f}\t50\t1",
      f"3\t0\t3\t85\t0\t0\t0\t0\t{region.destination.lat:.8f}\t{region.destination.lon:.8f}\t0\t1"]
    (out/"mission_seed.waypoints").write_text("\n".join(lines)+"\n")
    terrain.close(); return runtime
